/**
 * Алфавит кодов, которые человек читает с экрана и вводит руками.
 *
 * Живёт отдельно от `ids.ts` намеренно: тот файл генерирует коды и потому
 * тянет `node:crypto`, а этот алфавит нужен ещё и клиентской форме ввода.
 * Импортировать его оттуда означало бы затащить серверный модуль в браузер,
 * где сборщик честно отказывается это делать.
 *
 * Исключены 0, 1, I, L, O, U — символы, которые путают при чтении с
 * расстояния и при наборе с экранной клавиатуры без автозамены.
 *
 * Намеренно 31 символ, а не 32: отбрасываем 0/1/I/L/O/U важнее круглой
 * степени двойки. Из-за этого алфавит не степень двойки, и коды строятся
 * выборкой с отсевом, а не побитовой упаковкой.
 */
export const CODE_ALPHABET = '23456789ABCDEFGHJKMNPQRSTVWXYZ'

/** Сколько случайных бит даёт один символ: log2(31) ≈ 4.954. */
export const CODE_BITS_PER_CHAR = Math.log2(CODE_ALPHABET.length)

/**
 * Приводит введённый код к каноническому виду.
 *
 * Код на экране телевизора всегда заглавными, а человек набирает строчными
 * или с автозаменой после пробела. Приводить к верхнему регистру здесь, а не
 * в трёх местах по отдельности, — иначе рано или поздно одно из них забудет.
 */
export function normalizeCode(input: string): string {
  return input
    .toUpperCase()
    .split('')
    .filter((char) => CODE_ALPHABET.includes(char))
    .join('')
}