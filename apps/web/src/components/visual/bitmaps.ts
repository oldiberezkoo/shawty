/**
 * Один path из единичных квадратов.
 * `shape-rendering="crispEdges"` на SVG не даёт краям «поплыть».
 */
export function bitmapPath(rows: readonly string[]): string {
  const parts: string[] = []

  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] === '#') parts.push(`M${x} ${y}h1v1h-1z`)
    }
  })

  return parts.join('')
}
